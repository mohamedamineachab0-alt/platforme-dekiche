export function getCurriculumSubjects(level: string, stream: string): CurriculumSubject[] {
  if (level.startsWith("AP")) return PRIMARY_SUBJECTS[level] ?? [];
  if (level.startsWith("AM")) return MIDDLE_SUBJECTS[level] ?? [];
  if (level === "AS1") return SECONDARY_STREAM_SUBJECTS.COMMON_TRUNK.AS1 ?? [];
  return SECONDARY_STREAM_SUBJECTS[stream]?.[level] ?? [];
}

export function findCurriculumSubject(level: string, stream: string, title: string) {
  return getCurriculumSubjects(level, stream).find((subject) => subject.title === title) ?? null;
}

export function findCurriculumLesson(level: string, stream: string, subjectTitle: string, lessonTitle: string) {
  const subject = findCurriculumSubject(level, stream, subjectTitle);
  if (!subject?.lessons.includes(lessonTitle)) return null;
  return { subject, lessonTitle };
}
